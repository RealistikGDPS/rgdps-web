def rgb(index: int) -> RGB | None:
    if 0 <= index < len(PALETTE):
        return PALETTE[index]

    return None


def glow_colour(colour1: int, colour2: int, colour3: int) -> int:
    """The game falls back to the secondary colour, unless that is black, in
    which case the primary colour glows instead."""

    if colour3 >= 0:
        return colour3

    return colour1 if colour2 == _BLACK else colour2


def glow_visible(colour2: int, glow: bool) -> bool:
    """A black secondary colour always glows, whether or not glow is on."""

    return glow or colour2 == _BLACK


def white() -> RGB:
    return _WHITE
